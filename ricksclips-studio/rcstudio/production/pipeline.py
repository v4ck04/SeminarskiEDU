"""`produce`: topic -> finished Short, with approval gates.

Order: script -> (approve) -> voice -> storyboard (real timings) -> assets ->
subtitles -> audio mix -> preview -> (approve) -> final render -> QC ->
deliverables. Every stage is resumable; re-running `produce --project <slug>`
continues from the first stage that is not done.
"""
from __future__ import annotations

import json
from pathlib import Path

from .. import paths
from ..config import load_settings, load_voice_settings, resolve_production_settings
from ..utils import StudioError, read_json, say, write_json, write_text
from . import assets, qc, render, script as scriptmod, storyboard, subtitles, voice
from . import project as projmod


def settings_for(proj: dict) -> dict:
    s, _prov = resolve_production_settings(proj)
    return s


def write_brief(proj: dict) -> Path:
    """Script template + style brief for whoever writes the script (Claude Code or the user)."""
    settings = settings_for(proj)
    sdir = paths.scripts_root() / proj["slug"]
    write_json(sdir / "script.template.json", scriptmod.template(proj["topic"], int(settings["story"].get("target_duration_s", 40))))
    return write_text(sdir / "STYLE-BRIEF.md", "# Style brief for the script writer\n\n" + scriptmod.style_brief(settings) + "\n")


def stage_script(proj: dict, script_file: str | None = None, generate: bool | None = None, variants: int = 1,
                 research: bool | None = None, angle: str = "") -> str:
    """Returns 'done', 'waiting' (template written) or raises."""
    slug = proj["slug"]
    app = load_settings()
    settings = settings_for(proj)
    sdir = paths.scripts_root() / slug
    if script_file:
        data = json.loads(Path(script_file).read_text(encoding="utf-8"))
        data.setdefault("topic", proj["topic"])
        if isinstance(data.get("overrides"), dict):      # per-video look (e.g. palette) travels with the script
            from ..config import deep_merge
            proj["overrides"] = deep_merge(proj.get("overrides") or {}, data["overrides"])
            projmod.save(proj)
        val = scriptmod.write_outputs(slug, data, settings, app, note=f"imported from {script_file}")
    elif scriptmod.script_path(slug).exists() and not generate:
        val = scriptmod.write_outputs(slug, scriptmod.load(slug), settings, app, note="re-validated")
    else:
        want_api = generate if generate is not None else (app["script"].get("provider", "auto") in ("auto", "anthropic")
                                                         and scriptmod.claude_available())
        if not want_api:
            write_brief(proj)
            projmod.set_stage(proj, "script", "blocked", reason="waiting for script")
            say(f"No script yet. Write production/scripts/{slug}/script.json (template: script.template.json, "
                f"guidance: STYLE-BRIEF.md), then run `studio.py produce --project {slug}`. "
                "Inside Claude Code, Claude writes it for you; on the CLI set ANTHROPIC_API_KEY to generate it.", level="warn")
            return "waiting"
        res = research if research is not None else bool(app["script"].get("research", True))
        vs = scriptmod.generate(proj["topic"], settings, variants=variants or app["script"].get("variants", 1),
                                research=res, angle=angle, model=app["script"].get("model", "claude-opus-5-5"),
                                effort=app["script"].get("effort", "high"))
        for k, v in enumerate(vs, 1):
            write_json(sdir / f"script.variant{k}.json", v)
            write_text(sdir / f"script.variant{k}.md", scriptmod.to_markdown(v, scriptmod.validate(v, settings, app)))
        val = scriptmod.write_outputs(slug, vs[0], settings, app, note="generated by Claude API (variant 1)")
        if len(vs) > 1:
            say(f"{len(vs)} variants saved (script.variantN.md). Switch with `studio.py script {slug} --use-variant N`.")
    for e in val["errors"]:
        say(f"script error: {e}", level="fail")
    for w in val["warnings"]:
        say(f"script warning: {w}", level="warn")
    if val["errors"]:
        raise StudioError("Fix the script errors above, then run produce again.")
    st = val["stats"]
    say(f"Script OK: {st['words']} words, ~{st['estimated_duration_s']}s, {st['beats']} beats "
        f"-> production/scripts/{slug}/script.md", level="ok")
    sb = storyboard.build(scriptmod.load(slug), settings, slug)   # estimated timings, for review
    storyboard.save(sb)
    return "done"


def stage_voice(proj: dict, provider: str | None = None, force: bool = False) -> dict:
    say("Generating narration...", level="step")
    timing = voice.generate(proj["slug"], scriptmod.load(proj["slug"]), settings_for(proj), load_voice_settings(),
                            provider_name=provider, force=force)
    projmod.set_stage(proj, "voice", "done", provider=timing["provider"], duration=timing["duration"])
    return timing


def stage_storyboard(proj: dict) -> dict:
    slug = proj["slug"]
    timing = read_json(paths.project_dirs(slug)["voice"] / "timing.json")
    if not timing:
        raise StudioError("Generate the voice first - the storyboard uses the real narration timing.")
    sb = storyboard.build(scriptmod.load(slug), settings_for(proj), slug, timing)
    storyboard.save(sb)
    projmod.set_stage(proj, "storyboard", "done", scenes=len(sb["scenes"]), duration=sb["duration"])
    say(f"Storyboard: {len(sb['scenes'])} scenes, {sb['duration']:.1f}s -> production/storyboards/{slug}/storyboard.md", level="ok")
    return sb


def stage_assets(proj: dict, refresh: bool = False) -> dict:
    slug = proj["slug"]
    sb = read_json(paths.project_dirs(slug)["storyboard"] / "storyboard.json")
    say("Selecting visual assets...", level="step")
    man = assets.fetch(slug, sb, refresh=refresh)
    s = man["summary"]
    projmod.set_stage(proj, "assets", "done", **s)
    say(f"Assets: {s['ok']} sourced, {s['user']} yours, {s['generated']} generated, {s['placeholder']} placeholders",
        level="warn" if s["placeholder"] else "ok")
    return man


def stage_subtitles(proj: dict) -> dict:
    slug = proj["slug"]
    d = paths.project_dirs(slug)
    data = subtitles.build(slug, read_json(d["voice"] / "timing.json"), read_json(d["storyboard"] / "storyboard.json"),
                           settings_for(proj))
    projmod.set_stage(proj, "subtitles", "done", captions=data["count"])
    say(f"Subtitles: {data['count']} captions ({data['font']}) -> production/subtitles/{slug}/", level="ok")
    return data


def stage_preview(proj: dict) -> dict:
    s = settings_for(proj)
    if not projmod.stage_done(proj, "audio"):
        render.build_audio(proj["slug"], s)
    res = render.render(proj["slug"], s, preview=True)
    qc.run(proj["slug"], Path(res["file"]), final=False, settings=s)
    return res


def stage_final(proj: dict, allow_placeholders: bool = False) -> dict:
    s = settings_for(proj)
    res = render.render(proj["slug"], s, preview=False, allow_placeholders=allow_placeholders)
    rep = qc.run(proj["slug"], Path(res["file"]), final=True, settings=s)
    proj = projmod.load(proj["slug"])
    projmod.set_stage(proj, "qc", "done" if rep["verdict"] != "FAIL" else "failed", verdict=rep["verdict"])
    ex = render.export_deliverables(proj["slug"])
    say(f"Deliverables in production/exports/{proj['slug']}/: {', '.join(ex['files'])}", level="ok")
    return {"render": res, "qc": rep, "export": ex}


def produce(topic: str | None = None, slug: str | None = None, script_file: str | None = None,
            auto_approve: bool = False, provider: str | None = None, allow_placeholders: bool = False,
            generate: bool | None = None, variants: int = 1) -> dict:
    app = load_settings()
    if slug:
        proj = projmod.load(slug)
    elif topic:
        proj = projmod.create(topic)
        say(f"New project '{proj['slug']}' for: {topic}", level="step")
    else:
        raise StudioError("Give a topic or --project <slug>")
    slug = proj["slug"]
    wf = app["workflow"]

    changed = scriptmod.script_path(slug).exists() and \
        proj["stages"].get("script", {}).get("hash") != scriptmod.script_hash(scriptmod.load(slug))
    if not projmod.stage_done(proj, "script") or script_file or changed:
        if stage_script(proj, script_file=script_file, generate=generate, variants=variants) == "waiting":
            return {"slug": slug, "stopped_at": "script", "reason": "script needed"}
        proj = projmod.load(slug)
    if wf.get("require_script_approval", True) and not projmod.is_approved(proj, "script"):
        if auto_approve:
            projmod.approve(proj, "script", "auto-approved (--auto-approve)")
        else:
            say(f"Review production/scripts/{slug}/script.md, then approve: `studio.py approve {slug} script` "
                f"and run `studio.py produce --project {slug}`.", level="step")
            return {"slug": slug, "stopped_at": "script approval"}
    for stage, fn in (("voice", lambda p: stage_voice(p, provider)), ("storyboard", stage_storyboard),
                      ("assets", stage_assets), ("subtitles", stage_subtitles)):
        proj = projmod.load(slug)
        if not projmod.stage_done(proj, stage):
            fn(proj)
    proj = projmod.load(slug)
    if not projmod.stage_done(proj, "audio"):
        render.build_audio(slug, settings_for(proj))
    proj = projmod.load(slug)
    if not projmod.stage_done(proj, "preview"):
        stage_preview(proj)
        proj = projmod.load(slug)
    if wf.get("require_preview_approval", True) and not projmod.is_approved(proj, "preview"):
        if auto_approve:
            projmod.approve(proj, "preview", "auto-approved (--auto-approve)")
        else:
            say(f"Watch production/previews/{slug}/preview.mp4 (scene sheet: preview-contact.jpg). Approve with "
                f"`studio.py approve {slug} preview` then `studio.py produce --project {slug}`, or give feedback.", level="step")
            return {"slug": slug, "stopped_at": "preview approval"}
    proj = projmod.load(slug)
    if projmod.stage_done(proj, "final") and projmod.stage_done(proj, "qc"):
        qcrep = read_json(paths.project_dirs(slug)["export"] / "quality-report.json") or {}
        say(f"Already finished: production/exports/{slug}/final-video.mp4 (QC: {qcrep.get('verdict')}). "
            "Change something upstream to re-render, or run `studio.py render` to force it.", level="ok")
        return {"slug": slug, "stopped_at": None, "qc": qcrep}
    out = stage_final(proj, allow_placeholders=allow_placeholders)
    say(f"Done. Final video: production/exports/{slug}/final-video.mp4 (QC: {out['qc']['verdict']}). "
        f"Rate it with `studio.py feedback {slug}`.", level="ok" if out["qc"]["verdict"] != "FAIL" else "fail")
    return {"slug": slug, "stopped_at": None, **out}

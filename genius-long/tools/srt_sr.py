# Latin -> Cyrillic, digraphs first (lj, nj, dž), keeping capitalisation; words in LATIN_KEEP stay in Latin script
LATIN_KEEP = {"Long-Term", "Capital", "Management"}
DI = [("Dž", "Џ"), ("DŽ", "Џ"), ("dž", "џ"), ("Lj", "Љ"), ("LJ", "Љ"), ("lj", "љ"), ("Nj", "Њ"), ("NJ", "Њ"), ("nj", "њ")]
ONE = dict(zip("ABVGDĐEŽZIJKLMNOPRSTĆUFHCČŠabvgdđežzijklmnoprstćufhcčš",
               "АБВГДЂЕЖЗИЈКЛМНОПРСТЋУФХЦЧШабвгдђежзијклмнопрстћуфхцчш"))
def cyr_word(w):
    if w.strip(".,:;?!") in LATIN_KEEP: return w
    for a, b in DI: w = w.replace(a, b)
    return "".join(ONE.get(ch, ch) for ch in w)
def cyr(s): return re.sub(r"[^\s]+", lambda m: cyr_word(m.group(0)), s)

blocks = open("4-geniuses.en.srt", encoding="utf-8").read().strip().split("\n\n")
assert len(blocks) == len(SR), (len(blocks), len(SR))
for name, conv in (("4-geniuses.sr-Latn.srt", lambda s: s), ("4-geniuses.sr-Cyrl.srt", cyr)):
    out = []
    for b, t in zip(blocks, SR):
        n, tc = b.split("\n")[:2]
        lines = t.split("\n")
        if len(lines) == 1 and len(t) > 42: lines = textwrap.wrap(t, 42)
        out.append(f"{n}\n{tc}\n" + "\n".join(conv(x) for x in lines))
    open(name, "w", encoding="utf-8").write("\n\n".join(out) + "\n")
    print(name, len(out), "cues, longest line", max(len(l) for t in SR for l in t.split("\n")))
